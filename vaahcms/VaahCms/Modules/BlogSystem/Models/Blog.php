            $seo = $inputs['seo'];

            $item->seo()->updateOrCreate(
                [],
                [
                    'seo_title'       => $seo['seo_title'] ?? null,
                    'seo_description' => $seo['seo_description'] ?? null,
                    'seo_metatag'     => $seo['seo_metatag'] ?? [],
                ]
            );
        }

